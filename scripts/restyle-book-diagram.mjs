const paper = '#faf9f5';
const neutral = { stroke: '#5e5d59', surface: '#f5f4ed' };
const red = { stroke: '#a64b2f', surface: '#f5e7e0' };
const blue = { stroke: '#365b73', surface: '#e4edf2' };
const gold = { stroke: '#8c6318', surface: '#f6eacc' };
const colors = new Map([
  ['black', neutral], ['#000000', neutral],
  ['red', red], ['blue', blue], ['#0000ff', blue], ['gold', gold],
]);

const attributesByTag = {
  svg: new Set(['width', 'height', 'viewBox', 'xmlns', 'xmlns:xlink']),
  g: new Set(['id', 'class', 'transform']),
  title: new Set(),
  ellipse: new Set(['fill', 'stroke', 'cx', 'cy', 'rx', 'ry']),
  polygon: new Set(['fill', 'stroke', 'points']),
  path: new Set(['fill', 'stroke', 'd']),
  text: new Set(['text-anchor', 'x', 'y', 'font-family', 'font-size', 'fill']),
};
const children = {
  root: ['svg'],
  svg: ['graph'],
  graph: ['title', 'polygon', 'node', 'edge'],
  node: ['title', 'ellipse', 'text'],
  edge: ['title', 'path', 'polygon'],
};

// The pinned edition's Graphviz diagrams use this small, static SVG vocabulary.
// Retain the layout and labels while replacing presentation attributes only.
export function restyleDiagram(source) {
  if (!source.includes('<!-- Generated by graphviz version ')) return null;
  const start = source.indexOf('<svg');
  if (start < 0) return null;
  const body = source.slice(start).trim();
  if (!body.endsWith('</svg>')) return null;

  const svg = [];
  const stack = [];
  let offset = 0;
  for (const token of body.matchAll(/<!--[\s\S]*?-->|<(\/?)([\w-]+)((?:\s+[\w:-]+="[^"<>]*")*)\s*(\/?)>/g)) {
    const parent = stack.at(-1);
    const content = body.slice(offset, token.index);
    if (/[<>]/.test(content)) return null;
    if (content.trim() && !['text', 'title'].includes(parent?.kind)) return null;
    svg.push(content);
    offset = token.index + token[0].length;
    if (token[0].startsWith('<!--')) continue;

    const [, closing, tag, rawAttributes, selfClosing] = token;
    if (closing) {
      if (parent?.tag !== tag || rawAttributes || selfClosing) return null;
      stack.pop();
      svg.push('</' + tag + '>');
      continue;
    }
    if (!Object.hasOwn(attributesByTag, tag)) return null;
    const entries = [...rawAttributes.matchAll(/([\w:-]+)="([^"]*)"/g)];
    const attrs = Object.fromEntries(entries.map(([, name, value]) => [name, value]));
    if (Object.keys(attrs).length !== entries.length) return null;
    if (entries.some(([, name]) => !attributesByTag[tag].has(name))) return null;
    const kind = tag === 'g' ? attrs.class : tag;
    if (kind === 'svg' && token.index !== 0) return null;
    const allowed = Object.hasOwn(children, parent?.kind ?? 'root') ? children[parent?.kind ?? 'root'] : [];
    if (!allowed.includes(kind)) return null;
    if (!styleElement(tag, attrs, parent?.kind)) return null;

    const attributes = Object.entries(attrs).map(([name, value]) => ` ${name}="${value}"`).join('');
    svg.push('<' + tag + attributes + (selfClosing ? '/>' : '>'));
    if (!selfClosing) stack.push({ tag, kind });
  }
  if (stack.length || offset !== body.length) return null;
  return svg.join('') + '\n';
}

function styleElement(tag, attrs, parent) {
  if (tag === 'svg') {
    if (attrs.xmlns !== 'http://www.w3.org/2000/svg' || !attrs.viewBox || !attrs.width || !attrs.height) return false;
    delete attrs['xmlns:xlink'];
  } else if (tag === 'text') {
    attrs.fill = '#141413';
    attrs['font-family'] = 'Geist, Helvetica Neue, Arial, sans-serif';
    attrs['font-size'] = '13';
    attrs['font-weight'] = '500';
  } else if (tag === 'polygon' && parent === 'graph') {
    if (attrs.stroke !== 'transparent') return false;
    attrs.fill = paper;
  } else if (tag === 'ellipse' || tag === 'polygon' || tag === 'path') {
    const paint = colors.get(attrs.stroke);
    if (!paint) return false;
    attrs.stroke = paint.stroke;
    attrs['stroke-width'] = paint === neutral ? '1.15' : '1.55';
    if (tag === 'ellipse') attrs.fill = paint.surface;
    if (tag === 'polygon') attrs.fill = paint.stroke;
    if (tag === 'path') {
      attrs.fill = 'none';
      attrs['stroke-linecap'] = 'round';
    }
  }
  return true;
}
